// webui.h — 内置网页控制台
//
// 一个单文件 HTML，由 daemon 直接吐出来。为什么不做成静态文件：
// 部署时少一个"忘了推文件"的失败点；而且页面里的接口路径要跟着
// 服务的实际配置走，嵌在代码里反而更好维护。
//
// 页面做的事：
//   - <img src=".../stream"> 显示实时画面（MJPEG，浏览器原生支持，不需要 JS 解帧）
//   - 在画面上点击 / 长按 / 拖拽 → 换算成屏幕坐标 → 调触控接口
//   - 按键按钮 → 调按键接口
//   - 剪贴板查看与写入
//
// 刻意保持"零依赖、单文件"：不引任何前端框架或 CDN，
// 因为在设备上跑的服务未必能访问外网，而一个需要联网加载的
// 控制面板在离线环境里就是一块白屏。

#pragma once

